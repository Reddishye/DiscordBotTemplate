package es.redactado.menu.preset;

/** The semantic roles a menu needs an icon for. */
public enum IconKey {

    /** Confirmation of a successful outcome. */
    OK,

    /** Something failed. */
    ERROR,

    /** Something needs attention but is not a failure. */
    WARN,

    /** Neutral information. */
    INFO,

    /** Return to the previous view. */
    BACK,

    /** Move to the next page. */
    NEXT,

    /** Move to the previous page. */
    PREVIOUS,

    /** Dismiss the current view. */
    CLOSE,

    /** Accept a pending action. */
    CONFIRM,

    /** Reject a pending action. */
    CANCEL,

    /** Begin editing a value. */
    EDIT,

    /** Remove something. */
    DELETE,

    /** Follow a link. */
    LINK,

    /** Identify a person. */
    USER,

    /** Open configuration. */
    SETTINGS
}
